import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { applyChoices } from './dag-routing-choices.mjs';
import { choices } from './model-selection.mjs';
import { assessRouting, validateRouting } from './model-routing.mjs';

const menu = { claude: { fable: ['max'], opus: ['max'] }, codex: { 'fable/max': 'gpt-6.2-astra/ultra' } };
assert.deepEqual(choices([]).codex, {});
assert.ok(choices([]).claude.fable.includes('max'));
assert.throws(() => choices([{ from: 'haiku', to: 'local/low' }]), /치환표/);
const input = { scores: { C: 3, U: 3, R: 3, V: 3, F: 0 }, evidence: { C: 'system', U: 'open', R: 'data', V: 'manual', F: 'first' } };
const routing = { ...assessRouting(input), mode: 'auto' };
const row = { role: 'dev~ops', unit: 'build / test', agent: 'claude', model: 'fable', effort: 'max', base: 'fable/max', recommended: 'fable/max', routing };
const dag = { routingVersion: 2, choices: menu, nodes: [{ ...row, id: 'T01' }, { id: 'T02', fixed: true }, { ...row, id: 'T03' }] };
const drawing = createHash('sha256').update(JSON.stringify(dag)).digest('hex');
const manual = { model: 'fable', effort: 'max', mode: 'manual', codex: false, drawing };
const lock = { id: 'T01', data: manual };
const codex = { id: 'T03', data: { ...manual, mode: 'auto', codex: true } };
const result = applyChoices(dag, [lock, codex, { id: 'T01', data: { ...manual, drawing: 'previous' } }]);
const [first, , third] = result.dag.nodes;
assert.equal(first.routing.mode, 'manual');
assert.equal(first.base, first.recommended);
assert.equal(third.routing.mode, 'auto');
assert.equal(third.model, 'gpt-6.2-astra');
assert.equal(third.effort, 'ultra');
validateRouting(third.routing, 'codex', menu.codex);
assert.equal(dag.nodes[0].routing.mode, 'auto');
assert.equal(result.skipped, 1);
assert.throws(() => applyChoices(dag, [lock, lock]), /중복/);
assert.throws(() => applyChoices(dag, [{ ...lock, id: 'T02' }]), /고정/);
assert.throws(() => applyChoices(dag, [{ ...lock, data: { ...manual, model: 'opus', mode: 'auto' } }]), /추천/);
assert.throws(() => applyChoices(dag, [{ ...lock, data: { ...manual, effort: 'ultra' } }]), /모델/);
assert.throws(() => applyChoices(dag, [{ ...lock, data: { ...manual, drawing: 'previous' } }]), /버전/);
console.log('dag-routing-choices: task assignments, manual locks, runtime and revision validation passed');
