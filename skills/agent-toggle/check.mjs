import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { teamStructure } from './team.mjs'
import { manager } from './manager.mjs'

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-toggle-'))
try {
  const source = path.join(root, 'source')
  const project = path.join(root, 'project')
  fs.mkdirSync(path.join(source, 'references/demo/nested'), { recursive: true })
  fs.mkdirSync(project)
  fs.writeFileSync(path.join(source, 'demo.md'), 'agent: references/demo/nested/topic.md')
  fs.writeFileSync(path.join(source, 'references/demo/nested/topic.md'), 'topic')
  const m = manager(source, project)
  assert.equal(m.list()[0].state, 'off')
  m.set('demo', true)
  const topic = path.join(project, '.claude/agents/references/demo/nested/topic.md')
  const codex = path.join(project, '.codex/agents/demo.toml')
  const codexTopic = path.join(project, '.codex/agents/references/demo/nested/topic.md')
  assert.match(fs.readFileSync(codex, 'utf8'), /developer_instructions = "agent/)
  assert.ok(fs.readFileSync(codex, 'utf8').includes('.codex/agents/references/demo/nested/topic.md'))
  assert.ok(fs.readFileSync(path.join(project, '.claude/agents/demo.md'), 'utf8')
    .includes('.claude/agents/references/demo/nested/topic.md'))
  assert.equal(fs.readFileSync(codexTopic, 'utf8'), 'topic')
  fs.appendFileSync(codex, '!')
  assert.throws(() => m.set('demo', false))
  assert.equal(fs.existsSync(topic), true)
  fs.truncateSync(codex, fs.statSync(codex).size - 1)
  assert.equal(fs.readFileSync(topic, 'utf8'), 'topic')
  assert.equal(m.list()[0].state, 'on')
  fs.writeFileSync(path.join(project, '.codex/agents/local.toml'), 'local')
  assert.deepEqual(m.inventory(), [
    { name: 'demo', engine: 'Claude Code', scope: 'copied', state: 'on' },
    { name: 'demo', engine: 'Codex', scope: 'copied', state: 'on' },
    { name: 'local', engine: 'Codex', scope: 'project', state: 'on' },
  ])
  const local = path.join(project, '.codex/agents/local.toml')
  m.setProject('local', 'Codex', false)
  assert.equal(fs.existsSync(local), false)
  assert.equal(manager(source, project).inventory().find(r => r.name === 'local').state, 'off')
  fs.writeFileSync(local, 'new')
  assert.throws(() => m.setProject('local', 'Codex', true))
  assert.equal(fs.readFileSync(local, 'utf8'), 'new')
  fs.unlinkSync(local)
  m.setProject('local', 'Codex', true)
  assert.equal(fs.readFileSync(local, 'utf8'), 'local')
  assert.throws(() => m.setProject('../local', 'Codex', false))
  fs.appendFileSync(topic, '!')
  assert.throws(() => m.set('demo', false))
  fs.writeFileSync(topic, 'topic')
  m.setProject('demo', 'Codex', false)
  m.set('demo', false)
  assert.ok(!m.inventory().some(row => row.name === 'demo'))
  assert.equal(fs.existsSync(topic), false)
  assert.equal(fs.existsSync(codex), false)
  assert.equal(fs.existsSync(codexTopic), false)
  fs.writeFileSync(path.join(project, '.claude/agents/demo.md'), 'existing')
  assert.throws(() => m.set('demo', true))
  assert.throws(() => m.set('../demo', true))
  assert.equal(fs.readFileSync(path.join(project, '.claude/agents/demo.md'), 'utf8'), 'existing')
  const kit = path.join(source, 'package-kit')
  const kitAgent = path.join(kit, '.claude/agents/kit-agent.md')
  const kitTemplate = path.join(kit, '.claude/kit-agent/templates/brief.md')
  fs.mkdirSync(path.dirname(kitAgent), { recursive: true })
  fs.mkdirSync(path.dirname(kitTemplate), { recursive: true })
  fs.writeFileSync(kitAgent, 'Open .claude/kit-agent/templates/brief.md')
  fs.writeFileSync(kitTemplate, 'brief')
  assert.equal(m.list().find(row => row.name === 'package-kit').state, 'off')
  const installedAgent = path.join(project, '.claude/agents/kit-agent.md')
  const installedTemplate = path.join(project, '.claude/kit-agent/templates/brief.md')
  const installedCodex = path.join(project, '.codex/agents/kit-agent.toml')
  fs.mkdirSync(path.dirname(installedTemplate), { recursive: true })
  fs.writeFileSync(installedTemplate, 'existing')
  assert.throws(() => m.set('package-kit', true))
  assert.equal(fs.existsSync(installedAgent), false)
  fs.unlinkSync(installedTemplate)
  m.set('package-kit', true)
  const codexOriginal = fs.readFileSync(installedCodex)
  fs.appendFileSync(installedCodex, '\n# See `docs/codex-only.md`')
  const chart = teamStructure(project)
  const group = chart.groups.find(g => g.name === 'package')
  assert.equal(group.isTeam, false)
  assert.deepEqual(group.members.map(r => r.name), ['kit-agent'])
  assert.deepEqual(group.members[0].engines, ['Claude Code', 'Codex'])
  assert.deepEqual(group.members[0].references, ['.claude/kit-agent/templates/brief.md'])
  assert.deepEqual(group.members[0].editPaths, [])
  const roster = path.join(project, 'docs/harness/team-org.md')
  fs.mkdirSync(path.dirname(roster), { recursive: true })
  fs.writeFileSync(roster, '| `qa` | `kit-agent` | `local` | `team-qa` | tests |')
  fs.writeFileSync(path.join(path.dirname(roster), 'model-selection.md'),
    '| `kit-agent` | 별도 작업 | codex | test | low | |\n| `kit-agent` | 흐름 검증, 재검 | claude | opus | high | |\n| `*` | 기본 | claude | sonnet | medium | |')
  const qa = teamStructure(project).groups.find(g => g.name === 'qa')
  assert.equal(qa.isTeam, true)
  assert.deepEqual(qa.members[0].tasks, ['별도 작업', '흐름 검증', '재검'])
  assert.deepEqual(qa.members[0].assignments.map(a => a.model), ['test','opus', 'sonnet'])
  assert.equal(qa.lead, 'kit-agent')
  assert.deepEqual(qa.members.map(r => r.name), ['kit-agent'])
  assert.deepEqual(fs.readFileSync(installedAgent), fs.readFileSync(kitAgent))
  assert.deepEqual(fs.readFileSync(installedTemplate), fs.readFileSync(kitTemplate))
  assert.ok(fs.readFileSync(installedCodex, 'utf8').includes('.claude/kit-agent/templates/brief.md'))
  fs.writeFileSync(installedTemplate, 'edited')
  assert.throws(() => m.set('package-kit', false))
  assert.equal(fs.readFileSync(installedTemplate, 'utf8'), 'edited')
  fs.copyFileSync(kitTemplate, installedTemplate)
  m.setProject('kit-agent', 'Claude Code', false)
  const waiting = teamStructure(project).groups.find(g => g.name === 'qa')
  assert.equal(waiting?.waiting, true)
  assert.deepEqual(waiting.members.map(r => r.name), ['kit-agent'])
  assert.equal(waiting.members[0].state, 'off')
  assert.ok(m.inventory().some(r => r.name === 'kit-agent' && r.engine === 'Codex' && r.state === 'on'))
  fs.writeFileSync(installedCodex, codexOriginal)
  fs.renameSync(kit, kit + '-offline')
  m.set('package-kit', false)
  assert.ok(!m.inventory().some(row => row.name === 'kit-agent'))
  for (const file of [installedAgent, installedTemplate, installedCodex]) assert.ok(!fs.existsSync(file))
  // The index can point at another project document, including through a Markdown link relative to docs/.
  const docs = path.join(project, 'docs')
  fs.writeFileSync(path.join(project, 'product.md'), 'project canonical')
  fs.writeFileSync(path.join(root, 'private.md'), 'outside')
  fs.symlinkSync(root, path.join(project, 'linked'), process.platform === 'win32' ? 'junction' : 'dir')
  fs.writeFileSync(path.join(docs, 'DOCUMENTATION_INDEX.md'), [
    '## 문서', '| 위치 | 담는 것 | 정본 문서 | 관련 ID | 마지막으로 갱신한 phase | 상태 |',
    '| --- | --- | --- | --- | --- | --- |',
    '| `docs/01-product/` | PRD | [정본](../product.md) | | | 최신 |',
    '| `docs/02-requirements/` | SRS | [외부](../../private.md) | | | 최신 |',
    '| `docs/03-ui-ux/` | UI | `linked/private.md` | | | 최신 |',
  ].join('\n'))
  const legacy = teamStructure(project)
  assert.deepEqual(legacy.common.map(d => d.title), ['PRD','SRS','UI'])
  assert.deepEqual(legacy.files, {'product.md':'project canonical', '../private.md':null, 'linked/private.md':null})
  console.log('Passed')
} finally {
  fs.rmSync(root, { recursive: true, force: true })
}
